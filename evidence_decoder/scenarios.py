"""실험 시나리오.

지금까지 실험은 '감독 A' 하나에서 파생된 패킷뿐이었다. n 을 늘려도 같은 질문을
반복할 뿐이라 분산이 줄지 않고, 결론이 그 한 시나리오의 특성에 좌우될 위험이 있다.
서로 다른 주제 3종을 두어 주제 편향을 분리한다.

각 시나리오는 같은 골격을 갖는다.
  gold          정답에 필요한 근거 (key_points 와 1:1 대응)
  duplicate     gold[0] 과 같은 사실, 어휘는 다르게
  contradictory gold[1] 과 반대되는 진술
  hard_negative 주제어는 공유하되 초점만 빗나간 잡음
                (a) 대상 다름  (b) 측면 다름  (c) 매체·시기 다름
  easy_negative 주제가 아예 다른 잡음 (대조군)

asset_files 가 있으면 그 시나리오의 이미지·영상 근거가 실제 파일을 가리킨다.
비전 경로를 캡션 폴백이 아닌 정상 경로로 측정할 때 쓴다.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

from .schemas import Level

# (질문, required_operations, answer_constraints)
QuestionSpec = Tuple[str, List[str], List[str]]


@dataclass
class Scenario:
    id: str
    topic: str
    entities: List[str]
    questions: Dict[Level, QuestionSpec]
    gold_texts: List[str]
    gold_key_points: List[str]
    duplicate_texts: List[str]
    contradictory_texts: List[str]
    hard_negatives: List[str]
    easy_negatives: List[str]
    focus: Dict[str, List[str]]
    image_captions: Dict[str, List[str]] = field(default_factory=dict)
    video_captions: Dict[str, List[str]] = field(default_factory=dict)
    # {"image": ["image_000.jpg", ...], "video": [...]} - 실제 파일명
    asset_files: Dict[str, List[str]] = field(default_factory=dict)


