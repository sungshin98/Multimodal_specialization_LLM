SCENARIOS: Dict[str, Scenario] = {s.id: s for s in (FILM, FISH, BATTERY)}
DEFAULT_SCENARIO = FILM


def get(scenario_id: Optional[str]) -> Scenario:
    if not scenario_id:
        return DEFAULT_SCENARIO
    if scenario_id not in SCENARIOS:
        raise KeyError(f"알 수 없는 시나리오: {scenario_id} (가능: {sorted(SCENARIOS)})")
    return SCENARIOS[scenario_id]


def all_ids() -> Sequence[str]:
    return tuple(SCENARIOS)
